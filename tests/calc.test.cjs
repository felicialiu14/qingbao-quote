const assert = require('node:assert/strict');
const M = require('../calc.js');
assert.equal(M.factor('18'),'1.18');
assert.equal(M.factor('8'),'1.08');
assert.equal(M.factor('0'),'1.00');
assert.equal(M.factor('18.5'),'1.185');
assert.equal(M.calculate('720','7.2','18','direct'),11800n);
assert.equal(M.calculate('720','7.2','8','direct'),10800n);
assert.equal(M.calculate('813.6','7.2','18','tax'),11800n);
assert.equal(M.calculate('113','1','8','tax'),10800n);
assert.equal(M.calculate('0','7.2','18','direct'),0n);
assert.equal(M.calculate('100','1','0','direct'),10000n);
assert.equal(M.calculate('1.005','1','0','direct'),101n);
assert.equal(M.calculate('0.0049','1','0','direct'),0n);
assert.equal(M.calculate('999999999999.999999','0.000001','18','direct'),117999999999999999882n);
for (const bad of ['', '-1','abc','NaN','Infinity','1e3','1.0000001','1000000000000']) {
  assert.equal(M.calculate(bad,'7.2','18','direct'),null);
}
for(const rate of ['0','-7.2','','NaN']) assert.equal(M.calculate('720',rate,'18','direct'),null);
assert.equal(M.calculate('720','7.2','','direct'),null);
assert.equal(M.calculate('720','7.2','-1','direct'),null);
assert.equal(M.calculate('720','7.2','18','unknown'),null);
assert.equal(M.money(123456789n),'1,234,567.89');
assert.equal(M.money(101n,false),'1.01');
assert.equal(M.sumCosts(['0.004','0.004']),1n);
assert.equal(M.sumCosts(['813.6','720']),153360n);
assert.equal(Array.from({length:1000},()=>M.calculate('720','7.2','18','direct')).reduce((a,b)=>a+b,0n),11800000n);
assert.equal(M.panelAmount(14n,'550'),7700n);
assert.equal(M.panelAmount(14n,'600'),8400n);
assert.equal(M.panelAmount(15n,'550'),8250n);
assert.equal(M.panelAmount(13n,'555.5'),7222n);
assert.equal(M.panelAmount(0n,'550'),0n);
assert.equal(M.panelAmount(null,'550'),null);
for(const power of ['', '0', '-1', 'abc', '550W']) assert.equal(M.panelAmount(14n,power),null);
assert.equal(M.lineCost('0.8','550'),44000n);
assert.equal(M.lineCost('813.6'),81360n);
assert.equal(M.panelAmount(M.calculate('0.8','6.6','18','direct'),'550'),7700n);
console.log('All calculation checks passed, including panel pricing, decimal watts, display rounding, missing/invalid watts and per-panel costs.');
// Three-decimal solar prices must be calculated directly, not padded two-decimal prices.
assert.equal(M.calculate('0.8','6.6','18','direct',3),143n);
assert.equal(M.money(143n,true,3),'0.143');
assert.equal(M.panelAmount(143n,'550'),78650n);
assert.equal(M.money(78650n,true,3),'78.650');
assert.equal(M.calculate('0.1435','1','0','direct',3),144n);
assert.equal(M.calculate('0.14349','1','0','direct',3),143n);
assert.equal(M.panelAmount(143n,'555.5'),79437n);
assert.equal(M.money(0n,false,3),'0.000');
assert.equal(M.money(1234567n,false,3),'1234.567');
assert.equal(M.calculate('660','6.6','18','direct'),11800n);
console.log('Three-decimal component pricing and two-decimal other products passed.');
assert.equal(M.precisionFor('solar'),3);
for (const category of ['battery','inverter','accessory']) assert.equal(M.precisionFor(category),0);
for (const category of ['mount','cable','custom-category']) assert.equal(M.precisionFor(category),2);
assert.equal(M.money(M.calculate('1130','6.6','18','tax',M.precisionFor('inverter')),true,0),'179');
assert.equal(M.money(M.calculate('1130','6.6','18','tax',M.precisionFor('accessory')),true,0),'179');
assert.equal(M.money(M.calculate('660','6.6','18','direct',M.precisionFor('battery')),true,0),'118');
assert.equal(M.money(M.calculate('813.6','6.6','8','tax',M.precisionFor('mount')),true,2),'117.82');
assert.equal(M.calculate('178.5','1','0','direct',0),179n);
assert.equal(M.calculate('178.4999','1','0','direct',0),178n);
assert.equal(M.money(0n,true,0),'0');
assert.equal(M.money(1000n,true,0),'1,000');
console.log('Category-specific 3/0/2-decimal rounding passed.');
